#!/usr/bin/env python3
"""Prepare an offline Fig. S7 notebook from complete audited class exports.

Default/--dry-run validates and reports. --check requires an up-to-date notebook.
Only --write replaces it; this utility never executes cells or writes figures.
Historical plot functions retain their names and implementations; only their
paper-number keys and markdown headings change when Fig. 7 moves to S7.
"""
import argparse
import ast
import copy
import json
from pathlib import Path
import re

from fig7_cluster_mixed import OUTPUT, read_publication, require, sha

HERE = Path(__file__).resolve().parent
MARKER = '# Audited three-node Fig. S7; generated by update_fig7_cluster_mixed_notebook.py'
SEMANTIC_LABELS = {'8': 'fig:resp_valid', '9': 'fig:control-pressure',
                   '10': 'fig:control-lifecycle', '11': 'fig:objective-calibration'}


def without_comments(text):
    """Strip TeX comments, retaining escaped percent signs and line boundaries."""
    lines = []
    for line in text.splitlines(True):
        for index, char in enumerate(line):
            if char != '%':
                continue
            preceding = index
            while preceding and line[preceding-1] == '\\':
                preceding -= 1
            if (index-preceding) % 2 == 0:
                line = line[:index] + ('\n' if line.endswith('\n') else '')
                break
        lines.append(line)
    return ''.join(lines)


def expanded_main(main):
    """Expand literal input/include commands relative to the main TeX directory."""
    main = Path(main).resolve()
    root = main.parent

    def expand(path, stack):
        path = path.resolve()
        require(path not in stack, 'Recursive TeX input cycle: ' + str(path))
        text = without_comments(path.read_text())

        def include(match):
            relative = Path(match.group(1).strip())
            if not relative.suffix:
                relative = relative.with_suffix('.tex')
            candidate = root / relative
            if not candidate.exists():
                candidate = path.parent / relative
            return expand(candidate, (*stack, path))

        return re.sub(r'\\(?:input|include)\s*\{([^{}]+)\}', include, text)

    return expand(main, ())


def derive_paper_keys(main):
    """Count figure captions in expanded main, anticipating removal of old mixed.

    Paired control/lifecycle captions each increment the figure counter, while
    experimenttablecaption and algorithm captions do not. This intentionally
    supports the literal figure structure used by this manuscript, not TeX macros.
    """
    text = expanded_main(main)
    numbers = {}; counter = 0
    floats = re.finditer(r'\\begin\{figure\*?\}(.*?)\\end\{figure\*?\}', text, re.S)
    for floating in floats:
        body = floating.group(1)
        captions = list(re.finditer(r'\\caption(?:\s*\[[^\]]*\])?\s*\{', body))
        for i, caption in enumerate(captions):
            stop = captions[i+1].start() if i+1 < len(captions) else len(body)
            labels = re.findall(r'\\label\s*\{(fig:[^{}]+)\}', body[caption.end():stop])
            require(len(labels) <= 1, 'Ambiguous figure caption labels: ' + repr(labels))
            if labels == ['fig:revision-fourway-mixed']:
                continue
            counter += 1
            for label in labels:
                require(label not in numbers, 'Duplicate main figure label: ' + label)
                numbers[label] = str(counter)
    require(numbers.get('fig:nj-image') == '5' and
            numbers.get('fig:revision-fourway-workloads') == '6',
            'Main placement/Fig. 6 numbering changed; preserve their notebook payloads')
    require(all(label in numbers for label in SEMANTIC_LABELS.values()),
            'Main is missing a required semantic experiment figure label')
    keys = {'7': 'S7', **{old: numbers[label] for old, label in SEMANTIC_LABELS.items()},
            '12': 'S5', '13': 'S6'}
    require({keys[old] for old in SEMANTIC_LABELS} == {'7', '8', '9', '10'},
            'Expected four remaining main experiment figures numbered 7–10')
    return keys


def source(cell):
    return ''.join(cell['source'])


def unique_cell(notebook, predicate):
    found = [i for i, cell in enumerate(notebook['cells']) if predicate(source(cell))]
    require(len(found) == 1, f'Expected one target cell; found {found}')
    return found[0]


def replace_literal(text, node, replacement):
    lines = text.encode().splitlines(True)
    start = sum(map(len, lines[:node.lineno-1])) + node.col_offset
    stop = sum(map(len, lines[:node.end_lineno-1])) + node.end_col_offset
    return (text.encode()[:start] + replacement.encode() + text.encode()[stop:]).decode()


def dictionary(text, name):
    node = next(n.value for n in ast.parse(text).body if isinstance(n, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == name for t in n.targets))
    require(isinstance(node, ast.Dict), name + ' must be a literal dictionary')
    return node


def embedded_helper(helper):
    """Embed the actual figure function; no import or repository access at run time."""
    tree = ast.parse(helper)
    names = ('SYSTEMS', 'LABELS', 'COLORS', 'LEVELS', 'FACTORS')
    nodes = [node for node in tree.body if
        isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id in names
                                            for t in node.targets)
        or isinstance(node, ast.FunctionDef) and node.name == 'figure']
    require(len(nodes) == 6, 'Unexpected Fig. S7 helper structure')

    class Rename(ast.NodeTransformer):
        def visit_Name(self, node):
            if node.id in names:
                node.id = '_FIGS7_' + node.id
            return node

        def visit_FunctionDef(self, node):
            node.name = '_figs7_cluster_mixed_figure'
            return self.generic_visit(node)

    return ast.unparse(Rename().visit(ast.Module(body=nodes, type_ignores=[])))


def prepare(notebook, cells, manifest, hashes, helper, paper_keys=None):
    """Return a copy and exact changed-cell indices; never mutate the input."""
    result = copy.deepcopy(notebook)
    paper_keys = derive_paper_keys(HERE.parent/'main_slimmed.tex') if paper_keys is None else paper_keys
    require(set(paper_keys) == {'7', '8', '9', '10', '11', '12', '13'} and
            paper_keys['7'] == 'S7' and paper_keys['12'] == 'S5' and paper_keys['13'] == 'S6'
            and {paper_keys[k] for k in SEMANTIC_LABELS} == {'7', '8', '9', '10'},
            'Invalid semantic paper keys')
    current = any(MARKER in source(c) for c in result['cells'])
    heading = unique_cell(result, lambda s: s.startswith('## Fig. S7 —') if current
                          else s.startswith('## Fig. 7 —'))
    plot = unique_cell(result, lambda s: 'def plot_fig_s7():' in s if current
                       else 'def plot_fig_7():' in s)
    intro = unique_cell(result, lambda s: s.startswith('# Slimmed 实验图统一绘图 notebook'))
    style = unique_cell(result, lambda s: '\nFIGURE_STYLE = ' in s)
    fig6_heading = unique_cell(result, lambda s: s.startswith('## Fig. 6 —'))
    allowed = {intro, style, fig6_heading, heading, plot}
    prior_keys = {'7': 'S7' if current else '7'}
    # Old function names remain stable: these cells change only their key literal.
    for old, new in paper_keys.items():
        if old == '7':
            continue
        index = unique_cell(result, lambda s, old=old: f'def plot_fig_{old}():' in s)
        text = source(result['cells'][index])
        function = next(n for n in ast.parse(text).body if
                        isinstance(n, ast.FunctionDef) and n.name == f'plot_fig_{old}')
        assignment = next(n for n in function.body if isinstance(n, ast.Assign) and
                          any(isinstance(t, ast.Name) and t.id == 'key' for t in n.targets))
        previous = ast.literal_eval(assignment.value)
        require(isinstance(previous, str), 'Unexpected historical function key')
        prior_keys[old] = previous
        result['cells'][index]['source'] = replace_literal(text, assignment.value, repr(new)).splitlines(True)
        # Find its adjacent heading by cell position, avoiding label collisions
        # when existing main figures are reordered or this update is repeated.
        markdown = index-1
        text = source(result['cells'][markdown])
        require(text.startswith(f'## Fig. {previous} —'), 'Historical plot/heading mismatch')
        result['cells'][markdown]['source'] = text.replace(f'## Fig. {previous} —',
                                                          f'## Fig. {new} —', 1).splitlines(True)
        allowed.update((index, markdown))
    relabel = {prior_keys[old]: new for old, new in paper_keys.items()}
    text = source(result['cells'][style])
    for name in ('FIGURE_STYLE', 'FIGURE_FILES'):
        node = dictionary(text, name)
        edits = []
        for literal, value in zip(node.keys, node.values):
            key = ast.literal_eval(literal)
            if key in relabel:
                edits.append((literal, repr(relabel[key])))
            if key == ('S7' if current else '7'):
                if name == 'FIGURE_FILES':
                    edits.append((value, repr(OUTPUT)))
                else:
                    size = next(v for k, v in zip(value.keys, value.values)
                                if ast.literal_eval(k) == 'figsize')
                    edits.append((size, '[6.5, 2.7]'))
        # Apply back-to-front so UTF-8 AST offsets remain valid.
        for node, replacement in sorted(edits, key=lambda pair: (pair[0].lineno,
                                       pair[0].col_offset), reverse=True):
            text = replace_literal(text, node, replacement)
    result['cells'][style]['source'] = text.splitlines(True)
    text = source(result['cells'][intro])
    text = text.replace('正文 **Fig. 5–11**、附件 **Fig. S1–S2、S5–S6**',
                        '正文 **Fig. 5–10**、附件 **Fig. S1–S2、S5–S7**')
    text = text.replace('历史绘图单元保留原函数及设置键名12/13，分别对应当前附件图S5/S6。',
                        '原函数名8–13保留，图号设置键已对应正文7–10和附件S5/S6；混合截止期使用S7。')
    text = text.replace('Fig. 7保留旧实验三次运行区间',
                        'Fig. S7为三节点混合截止期实验五次配对重复的均值及95% Student t区间（df=4）')
    text = re.sub(r'Fig\. \d+保留全部五轮', f"Fig. {paper_keys['8']}保留全部五轮", text)
    text = re.sub(r'Fig\. \d+先按区组汇总', f"Fig. {paper_keys['10']}先按区组汇总", text)
    text = re.sub(r'图\d+原脚本', f"图{paper_keys['8']}原脚本", text)
    text = re.sub(r'图\d+在论文中', f"图{paper_keys['10']}在论文中", text)
    result['cells'][intro]['source'] = text.splitlines(True)
    text = source(result['cells'][fig6_heading])
    result['cells'][fig6_heading]['source'] = text.replace(
        '与 Fig. 7 的旧三次运行实验不同。',
        '混合截止期三节点实验见附件 Fig. S7。').splitlines(True)
    result['cells'][heading]['source'] = [
        '## Fig. S7 — 三节点混合截止期（附件）\n', '\n',
        '跨栏6.5×2.7英寸；两面板分别为100 ms和500 ms截止期。每个负载比较四个框架，保留全部24个单元。\n',
        '总输入负载为标定CPU容量的名义30%/80%/120%，实际总速率为116/309/463 req/s；每类占50%。\n',
        '均值和未裁剪95% Student t区间（df=4）由五次处理级配对重复计算；每次合并两个起点。\n',
        '点线为每一负载的实际每类输入速率（总速率/2），仅横跨对应的一组柱，不插值或连接相邻负载。\n',
        'goodput按固定半开10秒窗口内满足实际提交至返回截止期的有效返回计算；失败、超时均保留于输入分母。\n',
        '数据和绘图实现离线内嵌；历史单机数据与Fig. D2文件保持存档。\n',
        f'输出：`{OUTPUT}`。\n']
    # Read rates from the manifest so the text cannot drift from the embedded data.
    rates = manifest['rates_rps']['cpu']
    result['cells'][heading]['source'][3] = (
        '总输入负载为标定CPU容量的名义30%/80%/120%，实际总速率为'
        + '/'.join(str(rates[k]) for k in ('low', 'high', 'overload')) + ' req/s；每类占50%。\n')
    payload = dict(cells=cells, rates_rps=rates, capacity_rps=manifest['capacity_rps']['cpu'],
                   campaign=manifest['campaign'], duration_s=10, deadline_classes_ms=[100, 500],
                   load_factors=manifest['load_factors'])
    provenance = dict(hashes, plot_helper_sha256=sha(helper.encode()), status='PASS',
                      campaign=manifest['campaign'], treatments=60, origin_runs=120,
                      class_run_rows=120, cells=24, repetitions=5)
    code = MARKER + '\n'
    code += 'DATA["fig7_cluster_mixed"] = json.loads(' + repr(json.dumps(payload, separators=(',', ':'))) + ')\n'
    code += 'PROVENANCE["fig7_cluster_mixed"] = ' + repr(provenance) + '\n\n'
    code += embedded_helper(helper) + '\n\n'
    code += '''def plot_fig_s7():
    key = 'S7'
    start_plot(key, None)
    data = DATA['fig7_cluster_mixed']
    fig = _figs7_cluster_mixed_figure(data['cells'], data['rates_rps'],
                                    figsize=FIGURE_STYLE[key]['figsize'],
                                    colors=PALETTES['fourway'])
    PLOTTED_VALUES[key] = data['cells']
    return finish_plot(fig, key, tight=False)

plot_fig_s7();
'''
    compile(code, '<embedded Fig S7>', 'exec')
    result['cells'][plot]['source'] = code.splitlines(True)
    # Stale previews are removed only in the replaced mixed plot cell. The other
    # figure outputs remain byte-for-byte intact for later path-based comparison.
    if source(notebook['cells'][plot]) != code:
        result['cells'][plot]['outputs'] = []
        result['cells'][plot]['execution_count'] = None
    # Organize existing heading/plot pairs in current paper order, preserving
    # every cell ID and the relative positions of setup/data/export cells.
    pairs = []
    for index, cell in enumerate(result['cells']):
        if re.search(r'^def plot_fig_(?:[5-9]|1[0-3]|s[127])\(\):', source(cell), re.M):
            text = source(result['cells'][index-1])
            match = re.match(r'## Fig\. (S?\d+) —', text)
            require(match is not None, 'Missing adjacent plot heading')
            label = match.group(1)
            rank = 100+int(label[1:]) if label.startswith('S') else int(label)
            pairs.append((rank, index-1, result['cells'][index-1:index+1]))
    require(len(pairs) == 11, 'Expected 11 editable figure pairs')
    positions = sorted(i for _, index, _ in pairs for i in (index, index+1))
    require(positions == list(range(positions[0], positions[-1]+1)), 'Plot pairs must form one block')
    start, stop = positions[0], positions[-1]+1
    result['cells'][start:stop] = [c for _, _, pair in sorted(pairs) for c in pair]
    require(len(result['cells']) == len(notebook['cells']), 'Notebook cell count changed')
    by_id = {c['id']: c for c in result['cells']}
    require(len(by_id) == len(result['cells']) and set(by_id) == {c['id'] for c in notebook['cells']},
            'Notebook cell ID inventory changed')
    require(all(cell == by_id[cell['id']] for i, cell in enumerate(notebook['cells'])
                if i not in allowed), 'Unrelated notebook cell changed')
    return result, [i for i, (a, b) in enumerate(zip(notebook['cells'], result['cells'])) if a != b]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--publication', required=True, type=Path)
    parser.add_argument('--manifest', required=True, type=Path)
    parser.add_argument('--notebook', type=Path, default=HERE.parent / 'slimmed_experiment_figures.ipynb')
    parser.add_argument('--helper', type=Path, default=HERE / 'fig7_cluster_mixed.py')
    parser.add_argument('--main', type=Path, default=HERE.parent / 'main_slimmed.tex',
                        help='Derive semantic figure numbering from expanded main TeX')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--dry-run', action='store_true')
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    cells, manifest, hashes = read_publication(args.publication, args.manifest)
    original = args.notebook.read_bytes()
    paper_keys = derive_paper_keys(args.main)
    previous = json.loads(original)
    updated, changed = prepare(previous, cells, manifest, hashes, args.helper.read_text(), paper_keys)
    prior_cells = {cell['id']: cell for cell in previous['cells']}
    modified_ids = [cell['id'] for cell in updated['cells'] if cell != prior_cells[cell['id']]]
    reordered = [cell['id'] for cell in previous['cells']] != [cell['id'] for cell in updated['cells']]
    require(not args.check or not changed, f'Notebook needs update in cells {changed}')
    if args.write and changed:
        require(args.notebook.read_bytes() == original, 'Notebook changed during validation')
        temporary = args.notebook.with_suffix('.ipynb.figS7-tmp')
        with temporary.open('x') as stream:
            stream.write(json.dumps(updated, ensure_ascii=False, indent=1) + '\n')
        temporary.replace(args.notebook)
    print(json.dumps(dict(status='PASS', mode='write' if args.write else 'check' if args.check else 'dry-run',
                          changed_cells=changed, treatments=60, origin_runs=120, plotted_cells=24,
                          repetitions=5, notebook_written=bool(args.write and changed),
                          paper_keys=paper_keys, modified_cell_ids=modified_ids,
                          cell_order_changed=reordered, sha256=hashes), indent=2))


if __name__ == '__main__':
    main()
