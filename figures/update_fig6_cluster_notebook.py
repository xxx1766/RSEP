#!/usr/bin/env python3
"""Prepare a self-contained Fig. 6 notebook update from complete audited data.

Default/--dry-run validates and reports without writing. --check also requires
the notebook to be current. Only explicit --write replaces the notebook.
No notebook cell is executed and no figure file is written by this utility.
"""
import argparse
import ast
import copy
import csv
import hashlib
import io
import itertools
import json
import math
from pathlib import Path
import statistics

HERE = Path(__file__).resolve().parent
FIELDS = ('kind', 'level', 'pattern', 'system')
EXPECTED = set(itertools.product(('cpu', 'memory', 'io'), ('low', 'high'),
                               ('balanced', 'hotspot', 'burst'),
                               ('bare', 'kubeedge', 'ray', 'tide')))
T4 = 2.7764451051977987
MARKER = '# Audited three-node Fig. 6; generated by update_fig6_cluster_notebook.py'
FIG6_OUTPUT = 'revision-figs/evaluation/figD1_cluster.pdf'


def require(ok, message):
    if not ok:
        raise ValueError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def key(row):
    return tuple(row[name] for name in FIELDS)


def validate_publication(blobs):
    """Validate frozen exports and independently recompute plotted statistics."""
    audit = json.loads(blobs['audit.json'])
    manifest = json.loads(blobs['manifest.json'])
    for name, value in dict(status='PASS', treatments=360, origin_runs=720,
                            cells=72, repetitions=5).items():
        require(audit.get(name) == value, f'Incomplete publication audit: {name}')
    for name in ('runs.csv', 'cells.csv'):
        require(sha(blobs[name]) == audit['export_sha256'][name], f'SHA mismatch: {name}')
    require(sha(blobs['manifest.json']) == audit['manifest_sha256'], 'Manifest SHA mismatch')
    require(manifest['campaign'] == audit['campaign'], 'Campaign mismatch')
    require(manifest['repetitions'] == 5, 'Expected five repetitions')
    jobs = manifest['jobs']
    require(len(jobs) == 360 and len({j['id'] for j in jobs}) == 360, 'Manifest job inventory')
    require(set(audit['job_details']) == {j['id'] for j in jobs}, 'Audit job inventory')
    by_id = {j['id']: j for j in jobs}
    runs = list(csv.DictReader(io.StringIO(blobs['runs.csv'].decode())))
    cells = list(csv.DictReader(io.StringIO(blobs['cells.csv'].decode())))
    require(len(runs) == 360 and {r['job_id'] for r in runs} == set(by_id), 'Run inventory')
    grouped = {}
    for row in runs:
        job = by_id[row['job_id']]
        require(key(row) == key(job) and int(row['repeat']) == job['repeat'], 'Run/job mismatch')
        require(float(row['rate_rps']) == manifest['rates_rps'][row['kind']][row['level']], 'Rate mismatch')
        require(float(row['duration_s']) == manifest['duration_s'], 'Duration mismatch')
        value = float(row['goodput_rps'])
        require(math.isfinite(value) and value >= 0, 'Invalid run goodput')
        require(math.isclose(value, int(row['on_time_in_window']) / float(row['duration_s']),
                             rel_tol=1e-10, abs_tol=1e-10), 'Goodput/count mismatch')
        grouped.setdefault(key(row), []).append(row)
    require(set(grouped) == EXPECTED, 'Incomplete 72-cell factorial')
    selected = [r for r in cells if r['metric'] == 'goodput_rps']
    require(len(selected) == 72 and {key(r) for r in selected} == EXPECTED, 'Plotted cell inventory')
    for row in selected:
        observations = grouped[key(row)]
        require(len(observations) == 5 and {int(r['repeat']) for r in observations} == set(range(1, 6)),
                'Missing/duplicate repetition')
        require(int(row['n']) == 5, 'Every plotted cell must have n=5')
        values = [float(r['goodput_rps']) for r in observations]
        mean, sd = statistics.mean(values), statistics.stdev(values)
        se = sd / math.sqrt(5)
        expected = dict(mean=mean, sd=sd, se=se, ci95_halfwidth=T4 * se,
                        ci95_low=mean - T4 * se, ci95_high=mean + T4 * se)
        for name, value in expected.items():
            require(math.isfinite(float(row[name])) and math.isclose(float(row[name]), value,
                    rel_tol=1e-9, abs_tol=1e-9), f'Run/CI mismatch: {key(row)} {name}')
    return selected, manifest, {name: sha(data) for name, data in blobs.items()}


def embedded_helper(source):
    """Embed the actual helper implementation, with isolated global names."""
    tree = ast.parse(source)
    names = ('SYSTEMS', 'LABELS', 'COLORS', 'KINDS', 'PATTERNS')
    nodes = [node for node in tree.body if
             isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id in names for t in node.targets)
             or isinstance(node, ast.FunctionDef) and node.name == 'figure']
    require(len(nodes) == 6, 'Unexpected plotting helper structure')

    class Rename(ast.NodeTransformer):
        def visit_Name(self, node):
            if node.id in names:
                node.id = '_FIG6_' + node.id
            return node

        def visit_FunctionDef(self, node):
            node.name = '_fig6_cluster_figure'
            return self.generic_visit(node)

    return ast.unparse(Rename().visit(ast.Module(body=nodes, type_ignores=[])))


def source(cell):
    return ''.join(cell['source'])


def unique_cell(notebook, predicate):
    found = [i for i, cell in enumerate(notebook['cells']) if predicate(source(cell))]
    require(len(found) == 1, f'Expected one target cell; found {found}')
    return found[0]


def replace_literal(text, node, replacement):
    # AST columns are UTF-8 byte offsets, including when settings contain Chinese.
    lines = text.encode().splitlines(True)
    begin = sum(map(len, lines[:node.lineno - 1])) + node.col_offset
    end = sum(map(len, lines[:node.end_lineno - 1])) + node.end_col_offset
    return (text.encode()[:begin] + replacement.encode() + text.encode()[end:]).decode()


def prepare(notebook, cells, manifest, hashes, helper, capacity_labels=False):
    fractions = {'low': .3, 'high': .8} if capacity_labels else None
    if fractions is not None:
        for kind in ('cpu', 'memory', 'io'):
            capacity = float(manifest['capacity_rps'][kind])
            require(math.isfinite(capacity) and capacity > 0 and all(
                manifest['rates_rps'][kind][level] == round(max(2, capacity * fraction))
                for level, fraction in fractions.items()),
                'Capacity labels require rates rounded from 30%/80% of capacity')
    result = copy.deepcopy(notebook)
    heading = unique_cell(result, lambda s: s.startswith('## Fig. 6 —'))
    plot = unique_cell(result, lambda s: 'def plot_fig_6():' in s)
    intro = unique_cell(result, lambda s: s.startswith('# Slimmed 实验图统一绘图 notebook'))
    style = unique_cell(result, lambda s: '\nFIGURE_STYLE = ' in s)
    text = source(result['cells'][intro])
    old = 'Fig. 6–7为三次运行区间'
    new = 'Fig. 6为三节点实验五次配对重复的均值及95% Student t区间（df=4）；Fig. 7保留旧实验三次运行区间'
    require(old in text or new in text, 'Unexpected statistics introduction')
    text = text.replace(old, new)
    old_index = '正文 **Fig. 5–13**、附件 **Fig. S1–S2** 共11幅图可从数据重绘。'
    new_index = ('正文 **Fig. 5–11**、附件 **Fig. S1–S2、S5–S6** 共11幅图可从数据重绘。'
                 '历史绘图单元保留原函数及设置键名12/13，分别对应当前附件图S5/S6。')
    require(old_index in text or new_index in text, 'Unexpected figure index introduction')
    result['cells'][intro]['source'] = text.replace(old_index, new_index).splitlines(True)
    text = source(result['cells'][style])
    tree = ast.parse(text)
    assignment = next(n for n in tree.body if isinstance(n, ast.Assign)
                      and any(isinstance(t, ast.Name) and t.id == 'FIGURE_STYLE' for t in n.targets))
    require(isinstance(assignment.value, ast.Dict), 'FIGURE_STYLE must be a literal dictionary')
    item = next(v for k, v in zip(assignment.value.keys, assignment.value.values)
                if ast.literal_eval(k) == '6')
    size = next(v for k, v in zip(item.keys, item.values) if ast.literal_eval(k) == 'figsize')
    # Replace only Fig. 6's dimensions and destination; keep historical files.
    text = replace_literal(text, size, '[3.5, 4.0]')
    assignment = next(n for n in ast.parse(text).body if isinstance(n, ast.Assign)
                      and any(isinstance(t, ast.Name) and t.id == 'FIGURE_FILES' for t in n.targets))
    require(isinstance(assignment.value, ast.Dict), 'FIGURE_FILES must be a literal dictionary')
    output = next(v for k, v in zip(assignment.value.keys, assignment.value.values)
                  if ast.literal_eval(k) == '6')
    result['cells'][style]['source'] = replace_literal(text, output, repr(FIG6_OUTPUT)).splitlines(True)
    result['cells'][heading]['source'] = [
        '## Fig. 6 — 三节点多负载：低/高负载 × 平衡/热点/突发\n', '\n',
        '单栏3.5×4.0英寸，三行依次为CPU、Memory、Sync. I/O，两列依次为低/高负载；每面板比较平衡、热点、突发。\n',
        '完整360次处理、72个单元，每单元五次运行；误差棒为95% Student t区间（df=4）。\n',
        '纵轴为观测窗口内按时完成的 goodput（req/s），虚线为总到达率；保留全部结果和未裁剪区间。\n',
        '与 Fig. 7 的旧三次运行实验不同。数据和绘图实现均内嵌，来源为已通过完整性审计的 publication。\n',
        f'输出：`{FIG6_OUTPUT}`。\n']
    if capacity_labels:
        result['cells'][heading]['source'].insert(3,
            '图中输入负载标为各内核标定容量 $C_w$ 的名义30%/80%；实际发起速率取最近整数，保留在内嵌数据与附件协议中。goodput纵轴仍为req/s。\n')
    payload = dict(cells=cells, rates_rps=manifest['rates_rps'], campaign=manifest['campaign'],
                   duration_s=manifest['duration_s'], deadline_ms=manifest['deadline_ms'],
                   load_fractions=fractions)
    code = MARKER + '\n'
    code += 'DATA["fig6_cluster"] = json.loads(' + repr(json.dumps(payload, separators=(',', ':'))) + ')\n'
    provenance = dict(hashes, plot_helper_sha256=sha(helper.encode()), treatments=360,
                      cells=72, repetitions=5, status='PASS', campaign=manifest['campaign'])
    code += 'PROVENANCE["fig6_cluster"] = ' + repr(provenance) + '\n\n'
    code += embedded_helper(helper) + '\n\n'
    code += '''def plot_fig_6():
    key = '6'
    start_plot(key, None)
    data = DATA['fig6_cluster']
    fig = _fig6_cluster_figure(data['cells'], data['rates_rps'],
                              figsize=FIGURE_STYLE[key]['figsize'], colors=PALETTES['fourway'],
                              load_fractions=data.get('load_fractions'))
    PLOTTED_VALUES[key] = data['cells']
    return finish_plot(fig, key, tight=False)

plot_fig_6();
'''
    compile(code, '<embedded Fig6>', 'exec')
    result['cells'][plot]['source'] = code.splitlines(True)
    # Preserve unaffected outputs and all original DATA/PROVENANCE/ARCHIVES cells.
    if source(notebook['cells'][plot]) != code:
        result['cells'][plot]['outputs'] = []
        result['cells'][plot]['execution_count'] = None
    allowed = {intro, style, heading, plot}
    require(all(a == b for i, (a, b) in enumerate(zip(notebook['cells'], result['cells']))
                if i not in allowed), 'Unrelated cell changed')
    return result, [i for i, (a, b) in enumerate(zip(notebook['cells'], result['cells'])) if a != b]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--publication', type=Path, required=True)
    parser.add_argument('--manifest', type=Path, required=True)
    parser.add_argument('--notebook', type=Path, default=HERE.parent / 'slimmed_experiment_figures.ipynb')
    parser.add_argument('--helper', type=Path, default=HERE / 'fig6_cluster.py')
    parser.add_argument('--capacity-labels', action='store_true')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--dry-run', action='store_true')
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    blobs = {name: (args.publication / name).read_bytes() for name in ('runs.csv', 'cells.csv', 'audit.json')}
    blobs['manifest.json'] = args.manifest.read_bytes()
    cells, manifest, hashes = validate_publication(blobs)
    original = args.notebook.read_bytes()
    updated, changed = prepare(json.loads(original), cells, manifest, hashes,
                               args.helper.read_text(), capacity_labels=args.capacity_labels)
    require(not args.check or not changed, f'Notebook needs update in cells {changed}')
    if args.write and changed:
        require(args.notebook.read_bytes() == original, 'Notebook changed during validation')
        temporary = args.notebook.with_suffix('.ipynb.fig6-tmp')
        with temporary.open('x') as stream:
            stream.write(json.dumps(updated, ensure_ascii=False, indent=1) + '\n')
        temporary.replace(args.notebook)
    print(json.dumps(dict(status='PASS', mode='write' if args.write else 'check' if args.check else 'dry-run',
                          changed_cells=changed, treatments=360, plotted_cells=72, repetitions=5,
                          notebook_written=bool(args.write and changed), sha256=hashes), indent=2))


if __name__ == '__main__':
    main()
